def reproduction_fixture(tmp_path):
    m = json.loads((ROOT / "results/bit_revision/manifest.json").read_text())
    for rel in set(m["artifacts"]) | set(m["frozen_inputs_sha256"]):
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, p)
        if rel in m["artifacts"]:
            m["artifacts"][rel] = {"bytes": p.stat().st_size, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
    source_files = {"reproduce_bit.py": "# orchestrator\n", "pyproject.toml": "# dependency pins\n",
                    "scripts/verify_bit_claims.py": "# proof code\n"}
    for rel, content in source_files.items():
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    m["source_inputs_sha256"] = {rel: hashlib.sha256((tmp_path / rel).read_bytes()).hexdigest() for rel in source_files}
    manuscript = tmp_path / "manuscript"
    manuscript.mkdir()
    (manuscript / "main.tex").write_text("tested article", encoding="utf-8")
    m["manuscript_inputs_sha256"] = {"main.tex": hashlib.sha256((manuscript / "main.tex").read_bytes()).hexdigest()}
    return m


