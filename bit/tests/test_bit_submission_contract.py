def make_manuscript(tmp_path: Path, abstract_words: int = 180, **overrides) -> Path:
    m = tmp_path / "manuscript"
    m.mkdir(parents=True)
    abstract = " ".join(f"w{i}" for i in range(abstract_words))
    files = {
        "main.tex": GOOD_MAIN % abstract,
        "sec01.tex": GOOD_SEC,
        "declarations.tex": GOOD_DECL,
        "references.bib": GOOD_BIB,
        "ESM_1.tex": GOOD_ESM,
        "cover_letter.tex": GOOD_COVER,
        "article_numbers.tex": "\\expandafter\\gdef\\csname artnum@thm:main\\endcsname{1}\n",
        "Fig1.eps": "%!PS-Adobe-3.0 EPSF-3.0\n",
        "FigS1.eps": "%!PS-Adobe-3.0 EPSF-3.0\n",
        "sn-jnl.cls": "% class\n",
        "sn-mathphys-num.bst": "% bst\n",
    }
    files.update(overrides)
    for name, content in files.items():
        if content is None:
            continue
        (m / name).write_text(content, encoding="utf-8")
    return m


def rule(result: dict, rule_id: str) -> dict:
    for r in result["rules"]:
        if r["id"] == rule_id:
            return r
    raise KeyError(rule_id)


