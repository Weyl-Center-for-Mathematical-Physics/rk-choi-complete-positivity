@pytest.mark.parametrize("corruption", ["artifacts", "frozen", "source", "stage", "test_count", "empty_tests", "command_exit"])
def test_incomplete_reproduction_manifest_is_rejected(tmp_path, corruption):
    m = reproduction_fixture(tmp_path)
    if corruption == "artifacts":
        m["artifacts"] = {}
    elif corruption == "frozen":
        m["frozen_inputs_sha256"].pop(next(iter(m["frozen_inputs_sha256"])))
    elif corruption == "source":
        m.pop("source_inputs_sha256")
    elif corruption == "stage":
        m["stages"].pop()
    elif corruption == "test_count":
        m["tests_passed"] -= 1
    elif corruption == "empty_tests":
        m["tests_passed"] = m["tests_collected"] = 0
    else:
        m["stages"][0]["commands"][0]["exit"] = 1
    with pytest.raises(ValueError):
        bbp.validate_reproduction_manifest(tmp_path, m, manuscript=tmp_path / "manuscript")


