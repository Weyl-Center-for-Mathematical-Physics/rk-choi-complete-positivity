def test_pdf_text_preserves_utf8_quotes_and_dashes_under_other_host_locale(tmp_path, monkeypatch):
    expected = "We submit \u201ca paper\u201d\u2014it\u2019s ready.\n"
    real_run = bbp.subprocess.run
    real_which = bbp.shutil.which

    def utf8_tool(argv, **kwargs):
        # Exercise a real UTF-8-producing child while simulating the Windows cp1252 default.
        if kwargs.get("text") and not kwargs.get("encoding"):
            kwargs["encoding"] = "cp1252"
        command = [sys.executable, "-c", f"import sys; sys.stdout.buffer.write({expected.encode('utf-8')!r})"]
        return real_run(command, **kwargs)

    monkeypatch.setattr(bbp.shutil, "which", lambda name: "pdftotext" if name == "pdftotext" else real_which(name))
    monkeypatch.setattr(bbp.subprocess, "run", utf8_tool)
    assert bbp.pdf_text(tmp_path / "cover.pdf") == expected
