def test_review_variant_adds_lineno_option(tmp_path):
    m = make_manuscript(tmp_path)
    flat = bbp.flatten_tex(m / "main.tex")
    review = bbp.review_variant(flat)
    assert "\\documentclass[pdflatex,sn-mathphys-num,lineno]{sn-jnl}" in review
    assert review.count("lineno") == 1
    # the continuous ruler is restarted with a wider even-page offset so that four-digit numbers keep clear of the text
    assert "\\begin{document}\n" + bbp.REVIEW_RULER + "\n" in review
    assert "\\unsetvruler\\setvruler[12bp][1][1][3][1][1.18\\textwidth][18pt]" in review
    assert review.replace(bbp.REVIEW_RULER + "\n", "").replace(",lineno]", "]") == flat
    with pytest.raises(ValueError):
        bbp.review_variant(flat.replace("\\begin{document}", ""))


def test_flat_zip_writer_rejects_nested_and_absolute_names(tmp_path):
    f = tmp_path / "a.txt"
    f.write_text("x", encoding="utf-8")
    z = tmp_path / "out.zip"
    bbp.write_flat_zip(z, {"a.txt": f})
    with zipfile.ZipFile(z) as zf:
        assert zf.namelist() == ["a.txt"]
        assert zf.testzip() is None
    with pytest.raises(ValueError):
        bbp.write_flat_zip(tmp_path / "bad.zip", {"sub/a.txt": f})
    with pytest.raises(ValueError):
        bbp.write_flat_zip(tmp_path / "bad2.zip", {"../a.txt": f})


def test_flat_zip_is_deterministic(tmp_path):
    f = tmp_path / "a.txt"
    f.write_text("x", encoding="utf-8")
    z1, z2 = tmp_path / "1.zip", tmp_path / "2.zip"
    bbp.write_flat_zip(z1, {"a.txt": f})
    bbp.write_flat_zip(z2, {"a.txt": f})
    assert z1.read_bytes() == z2.read_bytes()


def test_zip_verification_detects_tampering(tmp_path):
    f = tmp_path / "a.txt"
    f.write_text("payload", encoding="utf-8")
    z = tmp_path / "out.zip"
    bbp.write_flat_zip(z, {"a.txt": f})
    ok = bbp.verify_flat_zip(z, {"a.txt": f})
    assert ok["crc_ok"] and ok["flat"] and ok["bytes_match"] and ok["members"] == 1
    f.write_text("changed", encoding="utf-8")
    assert not bbp.verify_flat_zip(z, {"a.txt": f})["bytes_match"]


def test_checksum_manifest_roundtrip(tmp_path):
    (tmp_path / "x.bin").write_bytes(b"abc")
    (tmp_path / "y.bin").write_bytes(b"def")
    text = bbp.sha256_manifest([tmp_path / "x.bin", tmp_path / "y.bin"], tmp_path)
    assert hashlib.sha256(b"abc").hexdigest() in text and "x.bin" in text
    assert bbp.verify_sha256_manifest(text, tmp_path) == []
    (tmp_path / "y.bin").write_bytes(b"xyz")
    assert bbp.verify_sha256_manifest(text, tmp_path) == ["y.bin"]


