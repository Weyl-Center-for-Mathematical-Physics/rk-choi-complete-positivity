import re
import sys
from fractions import Fraction
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import generate_bit_tables as gbt  # noqa: E402

TABLES = ROOT / "results" / "bit_revision" / "tables"
MANUSCRIPT = ROOT.parent / "manuscript"
HEADERS = {
    "extrapolation_table.tex": "% Table S2 data; generated from the archived records\n",
    "tolerance_sweep_table.tex": "% Table S3 data; generated from the archived records\n",
    "guard_telemetry_table.tex": "% Table S4 data; generated from the archived records\n",
}
GENERATED = {
    "extrapolation_table.tex": gbt.extrapolation_table,
    "tolerance_sweep_table.tex": gbt.tolerance_sweep_table,
    "guard_telemetry_table.tex": gbt.guard_telemetry_table,
}


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def tex_number(cell: str) -> Fraction | float:
    """Parse '$-1/2$', '$\\tfrac{97}{120000}$', '$7.92\\times10^{-4}$', '72', '0'."""
    s = cell.strip().strip("$").replace("\\,", "")
    m = re.fullmatch(r"(-?)\\tfrac\{(\d+)\}\{(\d+)\}", s)
    if m:
        return Fraction(int(m.group(2)), int(m.group(3))) * (-1 if m.group(1) else 1)
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)\\times10\^\{(-?\d+)\}", s)
    if m:
        return float(m.group(1)) * 10.0 ** int(m.group(2))
    m = re.fullmatch(r"-?\d+/\d+", s)
    if m:
        return Fraction(s)
    return Fraction(s)


def article_table(label: str) -> str:
    """The tabular* environment of the article table carrying `label`, from the working sections or, in the shipped
    archive, from the flattened article source `manuscript_source/main.tex`."""
    candidates = [MANUSCRIPT / "sec03_cp_criterion.tex", MANUSCRIPT / "sec06_certification_and_examples.tex", ROOT / "manuscript_source" / "main.tex"]
    for p in candidates:
        if p.exists():
            tex = p.read_text(encoding="utf-8")
            for m in re.finditer(r"\\begin\{table\}.*?\\end\{table\}", tex, re.S):
                if f"\\label{{{label}}}" in m.group(0):
                    return re.search(r"\\begin\{tabular\*\}.*?\\end\{tabular\*\}", m.group(0), re.S).group(0)
    pytest.skip(f"article source with table {label} not available (needs ../manuscript or manuscript_source/main.tex)")


def table_rows(tex: str) -> list[list[str]]:
    body = tex.split(r"\midrule", 1)[1]
    body = re.split(r"\\bottomrule|\\botrule", body)[0]
    rows = []
    for line in body.splitlines():
        line = line.strip()
        if not line or line.startswith("%"):
            continue
        cells = [c.strip() for c in line.rstrip("\\").split("&")]
        rows.append(cells)
    return rows


