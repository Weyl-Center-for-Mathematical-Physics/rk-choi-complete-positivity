def test_article_adaptive_table_matches_frozen_records():
    import csv

    with gbt.INPUTS["sweep"].open(newline="", encoding="utf-8") as f:
        sweep = {(r["policy"], float(r["tolerance"])): r for r in csv.DictReader(f)}
    v34 = json.loads(gbt.INPUTS["v34"].read_text(encoding="utf-8"))
    guard = {r["scenario"]: r for r in v34["scientifically_useful_candidate_guard_rows"]}
    table = article_table("tab:adaptive")
    rows = table_rows(table)
    assert len(rows) == 7
    policy_of = {"error only": "error_only", "guard, rotating fallback": "guard_rotating_fallback", "rotating frame": "rotating_frame", "Strang, exact subflows": "strang"}
    scenario_of = {"buffered (1)": "buffered_projection", "buffered (2)": "buffered_direct", "near saddle": "near_saddle_projection"}
    for case, policy, err, eig, dpf, stages in rows:
        if case == "boundary":
            src = sweep[(policy_of[policy], 1e-3)]
        else:
            src = guard[scenario_of[case]]
            assert policy == "guard"
        err_v = float(tex_number(err))
        assert abs(err_v - float(src["global_normalized_choi_error"])) <= 0.005 * abs(err_v), (case, policy)
        eig_src = float(src["minimum_step_choi_eigenvalue"])
        if eig.strip().startswith(r"$\ge"):
            assert eig_src >= -1e-15, (case, policy)
        else:
            eig_v = float(tex_number(eig))
            assert abs(eig_v - eig_src) <= 0.05 * abs(eig_v), (case, policy)
        if dpf.strip() == "--":
            # policies without the guard do not classify their accepted candidates
            assert src.get("controller_policy", "candidate_guard") != "candidate_guard" or case != "boundary" or policy == "error only"
            assert policy in ("error only", "rotating frame", "Strang, exact subflows"), (case, policy)
        else:
            d, p_, f_ = (int(v) for v in dpf.split("/"))
            assert d == int(float(src["direct_accepts"])) and p_ == int(float(src["projected_accepts"]))
            assert f_ == int(float(src["rotating_accepts"])) + int(float(src["exact_fallback_accepts"]))
            assert d + p_ + f_ == int(float(src["accepted_steps"])), (case, policy)
        assert int(stages) == int(float(src["rhs_stage_evaluations"])), (case, policy)


