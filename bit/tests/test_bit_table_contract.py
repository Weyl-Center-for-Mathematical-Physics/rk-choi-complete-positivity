ARTICLE_NAMES = {
    "Forward Euler": "Forward Euler",
    "Two-stage order two (Heun)": "Heun RK2",
    "SSPRK(3,3)": "SSPRK(3,3)",
    "Classical RK4": "Classical RK4",
    "Dormand--Prince 5 (principal)": "Dormand-Prince 5 principal formula",
    "Dormand--Prince 4 (embedded)": "Dormand-Prince embedded 4 formula",
    "Backward Euler": "Backward Euler",
    "Implicit midpoint": "Implicit midpoint",
}


def test_article_methods_table_matches_corollary_record():
    data = json.loads(gbt.INPUTS["corollary"].read_text(encoding="utf-8"))
    rec = {(r["method"], r["n"]): r for r in data["method_table"]}
    table = article_table("tab:methods")
    rows = table_rows(table)
    assert len(rows) == 9
    seen = set()
    for name, p, m, eta, coef, small in rows:
        p, m = int(p), int(m)
        eta_v, coef_v = tex_number(eta), tex_number(coef)
        if name.startswith("Richardson"):
            r = rec[("Classical RK4", 2)]
            assert (p, m) == (5, 6)
            assert eta_v == Fraction(r["defect_coefficient"]) == Fraction(-1, 4320)
        else:
            r = rec[(ARTICLE_NAMES[name], 2)]
            assert p == r["p"] and m == p + 1
            assert eta_v == Fraction(r["eta_p1"])
        G_m0 = 1 - Fraction(1, 2 ** (m - 1))
        assert coef_v == (-1) ** m * eta_v * G_m0, name
        assert small == ("CPTP" if coef_v > 0 else "non-CPTP"), name
        seen.add(name)
    assert seen == set(ARTICLE_NAMES) | {"Richardson extrapolate of RK4 ($n=2$)"}


