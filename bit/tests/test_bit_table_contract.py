def test_manifest_hashes_match_inputs_and_outputs():
    manifest = json.loads((TABLES / "manifest.json").read_text(encoding="utf-8"))
    for key, path in gbt.INPUTS.items():
        assert manifest["inputs"][key] == sha256(path), key
    for name in GENERATED:
        assert manifest["outputs"][name] == sha256(TABLES / name), name


@pytest.mark.parametrize("name", sorted(GENERATED))
def test_generated_table_is_deterministic_and_unedited(name):
    text = (TABLES / name).read_text(encoding="utf-8")
    header = HEADERS[name]
    assert gbt.HEADERS[name] == header
    assert text.startswith(header)
    assert text[len(header):] == GENERATED[name]()
    assert GENERATED[name]() == GENERATED[name]()


@pytest.mark.parametrize("name", sorted(GENERATED))
def test_generated_table_shape_and_rules(name):
    text = (TABLES / name).read_text(encoding="utf-8")
    assert r"\botrule" not in text  # article-class Online Resource uses booktabs
    assert text.count(r"\toprule") == 1 and text.count(r"\midrule") == 1 and text.count(r"\bottomrule") == 1
    spec = re.search(r"\\begin\{tabular\}\{@\{\}([lcr]+)@\{\}\}", text).group(1)
    ncol = len(spec)
    header = text.split(r"\toprule", 1)[1].split(r"\midrule", 1)[0]
    header_rows = [r for r in header.split(r"\\") if "&" in r]
    assert header_rows
    for hrow in header_rows:  # a grouped header row may span columns with \multicolumn{k}
        spans = [int(k) for k in re.findall(r"\\multicolumn\{(\d+)\}", hrow)]
        assert hrow.count("&") + 1 - len(spans) + sum(spans) == ncol, hrow
    for row in table_rows(text):
        assert len(row) == ncol, row


